impl ColorPalette {
    pub const fn new(red: [u8; 128], green: [u8; 128], blue: [u8; 128]) -> Self {
        return Self { red, green, blue };
    }

    pub fn rgb(&self, index: u8) -> (u8, u8, u8) {
        let index = (index as usize) % 128;
        (self.red[index], self.green[index], self.blue[index])
    }
}
